export const GLYPH_H = 7;
export const SPACE_W = 3;

/** Rasterise the font into an image: { w, h, albedo, normal, glyphs: {ch: {x, w}} }. White pixels, fully emissive. */
export function buildFont() {
  const keys = Object.keys(G), glyphs = {};
  let W = 1; for (const k of keys) W += G[k].split('/')[0].length + 1;
  const H = GLYPH_H + 2, albedo = new Uint8ClampedArray(W * H * 4), normal = new Uint8ClampedArray(W * H * 4);
  for (let i = 0; i < W * H; i++) { normal[i * 4] = 128; normal[i * 4 + 1] = 128; normal[i * 4 + 2] = 255; normal[i * 4 + 3] = 255; }
  let x = 1;
  for (const k of keys) {
    const rows = G[k].split('/'), w = rows[0].length;
    rows.forEach((row, y) => { for (let i = 0; i < w; i++) if (row[i] === '#') { const j = ((y + 1) * W + x + i) * 4; albedo[j] = albedo[j + 1] = albedo[j + 2] = albedo[j + 3] = 255; } });
    glyphs[k] = { x, w };
    x += w + 1;
  }
  return { w: W, h: H, albedo, normal, glyphs };
}

export function textWidth(font, str, scale = 1) {
  let w = 0;
  for (const ch of String(str).toUpperCase()) { const g = font.glyphs[ch]; w += (g ? g.w : SPACE_W) + 1; }
  return Math.max(0, w - 1) * scale;
}

/** Break text into lines no wider than maxW. */
export function wrap(font, str, maxW, scale = 1) {
  const lines = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (line && textWidth(font, t, scale) > maxW) { lines.push(line); line = word; } else line = t;
    }
    lines.push(line);
  }
  return lines;
}
